#!/usr/bin/env python3
"""Precision needed: the ENOB an analogue chain must reach to match each number format's own
rounding error, by the series' rule, extended to the low-bit formats AI hardware now uses.

The rule is the one in data/foptinf_analysis/flop_share.py (results.md section 6):

    relative RMS error = crest x 2^-ENOB x 2/sqrt(12)  =>  ENOB = log2(crest x 2 / (sqrt(12) x rel))

where rel is the format's own relative RMS rounding error on the reference signal (a causal
FFT convolution of length 4,096) and crest is that signal's peak-to-RMS ratio. The reference
signal is regenerated by replaying the series' random stream (seed 20261004) through the same
calls, so BF16, INT8 and FP8 E4M3 come out bit-for-bit as the series has them (10.3, 8.0, 6.3);
the tests check this before any new value is trusted.

The simulator's approximate mode (e16) reports a different measure: "effective bits =
(SNR - 1.76)/6.02 of the whole FFT's relative error", i.e. SNR = -20 log10(rel). The two differ
by the crest term, so the comparison chart puts both "needed" and "available" in the e16
measure, converted from the same rel. The conversion is exact; the test checks it.

Formats (definitions from the cited specs, see sources/quotes.md):
  BF16, FP8 E4M3, INT8   the series' own rounding functions, copied unchanged
  FP8 E5M2               2 mantissa bits, max 57,344, subnormals below 2^-14, per-tensor scale
  INT4                   symmetric, levels -7..7, per-tensor scale (and per block of 32)
  FP4 E2M1               values 0, 0.5, 1, 1.5, 2, 3, 4, 6; per-tensor scale to 6
  MXFP4                  FP4 E2M1 in blocks of 32 sharing a power-of-two (E8M0) scale
  NVFP4                  FP4 E2M1 in blocks of 16 sharing an FP8 E4M3 scale

numpy only. Writes analysis/out/precision_needed.json.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parent / "out"
SEED = 20261004          # flop_share.py main()
REF_LEN = 4096           # results.md section 6: "same metric, length 4,096"


# ─────────────────────────────── the series' signal, replayed exactly ──
def pow2_at_least(n: int) -> int:
    return 1 << (n - 1).bit_length()


def causal_fft_conv(u: np.ndarray, h: np.ndarray) -> np.ndarray:
    n = pow2_at_least(2 * len(u))
    return np.fft.irfft(np.fft.rfft(u, n) * np.fft.rfft(h, n), n)[: len(u)]


def reference_signal() -> np.ndarray:
    """The length-4,096 causal convolution output that flop_share.py's precision() measures.

    Replays every draw flop_share.py makes from its generator before that point: checks()
    draws u, h (1,024 each) and a 256 x 64 block; precision() at length 256 draws u, h, then
    one noise vector per ENOB (4..14, six), 4 for the 4-pass average, 16 for the 16-pass
    average and 2 for the two digit planes; then length 4,096 draws u and h."""
    rng = np.random.default_rng(SEED)
    rng.standard_normal(1024); rng.standard_normal(1024); rng.standard_normal((256, 64))
    s = 256
    rng.standard_normal(s); rng.standard_normal(s)
    for _ in range(6 + 4 + 16 + 2):
        rng.standard_normal(s)
    u = rng.standard_normal(REF_LEN)
    h = rng.standard_normal(REF_LEN) * np.exp(-np.arange(REF_LEN) / (REF_LEN / 8))
    return causal_fft_conv(u, h)


def crest(y: np.ndarray) -> float:
    return float(np.max(np.abs(y)) / np.sqrt(np.mean(y ** 2)))


def rel_rms(a: np.ndarray, ref: np.ndarray) -> float:
    return float(np.sqrt(np.mean((a - ref) ** 2) / np.mean(ref ** 2)))


# ─────────────────────────────────── the series' formats, unchanged ──
def bf16(x: np.ndarray) -> np.ndarray:
    b = x.astype(np.float32).view(np.uint32)
    b = (b + 0x7FFF + ((b >> 16) & 1)) & 0xFFFF0000            # round to nearest even
    return b.astype(np.uint32).view(np.float32).astype(np.float64)


def fp8_e4m3(x: np.ndarray) -> np.ndarray:
    """Round to FP8 E4M3 (3 mantissa bits; max 448; subnormals below 2^-6), per-tensor scaled
    so the largest magnitude maps to 448, as inference engines do."""
    scale = 448.0 / np.max(np.abs(x))
    y = x * scale
    e = np.floor(np.log2(np.maximum(np.abs(y), 2.0 ** -6)))
    q = 2.0 ** (e - 3)
    return np.round(y / q) * q / scale


def int8(x: np.ndarray) -> np.ndarray:
    scale = 127.0 / np.max(np.abs(x))
    return np.round(x * scale) / scale


# ───────────────────────────────────────────── the new formats ──
def minifloat(y: np.ndarray, man_bits: int, min_normal_exp: int, max_val: float) -> np.ndarray:
    """Round an already-scaled array to a minifloat with ``man_bits`` mantissa bits, normal
    exponents from ``min_normal_exp`` up (subnormals below, same step), saturating at max_val.
    The same construction as the series' fp8_e4m3."""
    e = np.floor(np.log2(np.maximum(np.abs(y), 2.0 ** min_normal_exp)))
    q = 2.0 ** (e - man_bits)
    return np.clip(np.round(y / q) * q, -max_val, max_val)


def fp8_e5m2(x: np.ndarray) -> np.ndarray:
    """FP8 E5M2: 2 mantissa bits, max 57,344, subnormals below 2^-14; per-tensor scale."""
    scale = 57344.0 / np.max(np.abs(x))
    return minifloat(x * scale, 2, -14, 57344.0) / scale


def fp4_e2m1_scaled(y: np.ndarray) -> np.ndarray:
    """FP4 E2M1 on an already-scaled array: 1 mantissa bit, min normal 2^0, subnormal 0.5,
    max 6, so the magnitudes are 0, 0.5, 1, 1.5, 2, 3, 4, 6."""
    return minifloat(y, 1, 0, 6.0)


def fp4_e2m1(x: np.ndarray) -> np.ndarray:
    """FP4 E2M1 with one per-tensor scale (largest magnitude -> 6), as the series scales FP8."""
    scale = 6.0 / np.max(np.abs(x))
    return fp4_e2m1_scaled(x * scale) / scale


def blocks(x: np.ndarray, k: int) -> np.ndarray:
    if len(x) % k:
        raise ValueError("length must be a multiple of the block size")
    return x.reshape(-1, k)


def mxfp4(x: np.ndarray, k: int = 32) -> np.ndarray:
    """OCP MX FP4: blocks of 32 share a power-of-two scale X = 2^(floor(log2 amax) - emax_elem),
    emax_elem = 2 for E2M1; elements are x/X rounded to E2M1, saturating at 6."""
    b = blocks(x, k)
    amax = np.max(np.abs(b), axis=1, keepdims=True)
    X = 2.0 ** (np.floor(np.log2(np.where(amax > 0, amax, 1.0))) - 2)
    return (fp4_e2m1_scaled(b / X) * X).reshape(-1)


def nvfp4(x: np.ndarray, k: int = 16) -> np.ndarray:
    """NVFP4: blocks of 16 share an FP8 E4M3 scale (amax/6 rounded to E4M3), under a per-tensor
    FP32 scale that maps the largest block scale onto E4M3's range (max 448)."""
    b = blocks(x, k)
    amax = np.max(np.abs(b), axis=1, keepdims=True)
    raw = amax / 6.0
    t = 448.0 / np.max(raw)                                  # per-tensor FP32 scale
    s = minifloat(raw * t, 3, -6, 448.0) / t                 # block scale, stored in E4M3
    s = np.where(s > 0, s, 1.0)
    return (fp4_e2m1_scaled(b / s) * s).reshape(-1)


def int4(x: np.ndarray) -> np.ndarray:
    """Symmetric INT4 (levels -7..7), one per-tensor scale."""
    scale = 7.0 / np.max(np.abs(x))
    return np.clip(np.round(x * scale), -7, 7) / scale


def int4_g32(x: np.ndarray, k: int = 32) -> np.ndarray:
    """Symmetric INT4 with one scale per block of 32 (group-wise, as low-bit weight and KV
    quantisers use)."""
    b = blocks(x, k)
    scale = 7.0 / np.max(np.abs(b), axis=1, keepdims=True)
    return (np.clip(np.round(b * scale), -7, 7) / scale).reshape(-1)


# name -> (function, short description, bits per value including the block scale's share)
FORMATS = {
    "BF16":           (bf16, "the series' rounding (8 mantissa bits incl. hidden)", 16.0),
    "FP8 E4M3":       (fp8_e4m3, "the series' rounding, per-tensor scale", 8.0),
    "INT8":           (int8, "the series' rounding, per-tensor scale", 8.0),
    "FP8 E5M2":       (fp8_e5m2, "per-tensor scale", 8.0),
    "INT4":           (int4, "symmetric, per-tensor scale", 4.0),
    "INT4 g32":       (int4_g32, "symmetric, one scale per 32 values", 4.0 + 16 / 32),
    "FP4 E2M1":       (fp4_e2m1, "per-tensor scale", 4.0),
    "MXFP4":          (mxfp4, "E2M1, block 32, E8M0 scale", 4.0 + 8 / 32),
    "NVFP4":          (nvfp4, "E2M1, block 16, E4M3 scale", 4.0 + 8 / 16),
}
SERIES_FORMATS = ("BF16", "FP8 E4M3", "INT8")
SERIES_ENOB = {"BF16": 10.3, "INT8": 8.0, "FP8 E4M3": 6.3}     # results.md section 6, as printed


# ───────────────────────────────────────────────────── the rules ──
def enob_needed(rel: float, c: float) -> float:
    """The series' rule, inverted: ENOB = log2(crest x 2 / (sqrt(12) x rel))."""
    return math.log2(c * 2 / (math.sqrt(12) * rel))


def rule_rel(enob: float, c: float) -> float:
    """The series' rule forward: rel = crest x 2^-ENOB x 2/sqrt(12)."""
    return c * 2.0 ** -enob * 2 / math.sqrt(12)


def snr_bits(rel: float) -> float:
    """e16's measure: (SNR - 1.76)/6.02 with SNR = -20 log10(rel)."""
    return (-20 * math.log10(rel) - 1.76) / 6.02


def rel_from_snr_bits(bits: float) -> float:
    return 10 ** (-(bits * 6.02 + 1.76) / 20)


def series_enob_from_snr_bits(bits: float, c: float) -> float:
    """An e16 'effective bits' figure restated in the series' ENOB (same rel, same crest)."""
    return enob_needed(rel_from_snr_bits(bits), c)


def compute() -> dict:
    y = reference_signal()
    c = crest(y)
    rows = {}
    for name, (fn, desc, bpv) in FORMATS.items():
        r = rel_rms(fn(y), y)
        rows[name] = {"rel_rms": r, "enob_needed": enob_needed(r, c), "snr_bits": snr_bits(r),
                      "description": desc, "bits_per_value": bpv}
    return {"reference": {"length": REF_LEN, "seed": SEED, "crest": c},
            "rule": "ENOB = log2(crest x 2 / (sqrt(12) x rel)); e16 bits = (-20 log10 rel - 1.76)/6.02",
            "crest_offset_bits": enob_needed(1.0, c) - snr_bits(1.0),
            "formats": rows}


def main() -> None:
    OUT.mkdir(exist_ok=True)
    res = compute()
    (OUT / "precision_needed.json").write_text(json.dumps(res, indent=1) + "\n")
    print(f"crest {res['reference']['crest']:.4f}; offset {res['crest_offset_bits']:.4f} bits")
    for k, v in res["formats"].items():
        print(f"{k:10s} rel {v['rel_rms']:.3e}  ENOB {v['enob_needed']:.2f}  e16 bits {v['snr_bits']:.2f}")


if __name__ == "__main__":
    main()
